const choose = harness();
const original = choose.state().draft;
choose.click('view', { view: 'result' });
assert.equal(choose.state().view, 'input', 'result cannot bypass step two');
choose.click('calculate');
assert.equal(choose.pending(), 0, 'input cannot calculate directly');
choose.click('continue');
assert.equal(choose.state().view, 'choose');
assert.deepEqual(choose.state().draft, original, 'entering step two does not mutate inputs');
assert.match(choose.markup(), /앞에서 입력한 장소 · 2곳/);
assert.match(choose.markup(), /예시 추천/);
assert.equal(choose.state().map.showRoute, false);
assert.doesNotMatch(choose.markup(), /<polyline/);
const first = 'demo-gion', second = 'demo-manga';
choose.click('choose-toggle', { id: first });
choose.click('choose-toggle', { id: second });
assert.match(choose.markup(), /추천에서 고른 장소 · 2곳/);
assert.deepEqual(choose.state().draft.days[0].placeIds, [...original.days[0].placeIds, first, second]);
const marks = choose.state().map.places;
assert.equal(new Set(marks.map((mark) => mark.id)).size, marks.length);
assert.equal(marks.find((mark) => mark.id === first).state, 'routed');
assert.equal(choose.state().map.showRoute, false);
choose.click('choose-toggle', { id: 'demo-kiyomizu' });
assert.ok(choose.state().draft.days[0].placeIds.includes('demo-kiyomizu'), 'base place cannot be removed via recommendations');
choose.click('view', { view: 'input' });
choose.click('tag', { tag: 'culture' });
choose.click('tag', { tag: 'nature' });
choose.click('tag', { tag: 'activity' });
choose.click('continue');
assert.match(choose.markup(), /data-id="demo-gion" aria-pressed="true"/);
choose.click('choose-toggle', { id: first });
assert.ok(!choose.state().draft.days[0].placeIds.includes(first));
choose.click('day', { day: '1' });
assert.ok(!choose.state().map.places.some((place) => place.id === second), 'another day owns this pick');
choose.click('choose-toggle', { id: second });
assert.ok(!choose.state().draft.days[1].placeIds.includes(second));
choose.click('choose-toggle', { id: 'demo-railway' });
assert.ok(choose.state().draft.days[1].placeIds.includes('demo-railway'));
choose.click('view', { view: 'input' });
choose.change('day-count', '1');
choose.change('day-count', '2');
choose.click('continue');
assert.match(choose.markup(), /추천에서 고른 장소 · 1곳/, 'hidden day ownership restored');
choose.click('choose-toggle', { id: 'demo-railway' });
choose.click('day', { day: '0' });
choose.click('view', { view: 'input' });
choose.click('remove', { id: second });
choose.click('search');
choose.dialogClick({ addId: second });
choose.dialogClick({ action: 'confirm-search' });
choose.click('continue');
assert.match(choose.markup(), /추천에서 고른 장소 · 0곳/);
choose.click('choose-toggle', { id: second });
assert.ok(choose.state().draft.days[0].placeIds.includes(second), 're-added input becomes protected base');
choose.click('calculate');
const during = choose.state().draft;
choose.click('choose-toggle', { id: 'demo-railway' });
assert.deepEqual(choose.state().draft, during, 'cannot toggle while calculating');
await choose.settle();
assert.equal(choose.state().view, 'result');
assert.ok(choose.state().result.days[0].order.includes(second));

