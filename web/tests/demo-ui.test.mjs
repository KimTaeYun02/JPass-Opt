import assert from 'node:assert/strict';
import * as model from '../src/demo-model.ts';
import { harness } from './demo-harness.mjs';

const demo = harness();
assert.match(demo.markup(), /여행 정보 입력/);
assert.match(demo.markup(), /station-marker/);
assert.doesNotMatch(demo.markup(), /map-title|map-bottom-copy|recommend-art/);
demo.click('continue');
demo.click('calculate');
await demo.settle();
assert.match(demo.markup(), /class="route-list"/);
assert.match(demo.markup(), /aria-expanded="false"/);
assert.ok(demo.markup().includes(model.dateAt('2026-11-10', 0) + '부터'));
demo.click('toggle-nearby');
assert.match(demo.markup(), /aria-expanded="true"/);
assert.match(demo.markup(), /class="route-list"/);
assert.match(demo.markup(), /class="recommend-card"/);
const addition = model.recommendations(model.initialDraft(), 0)[0].id;
demo.click('recommend-add', { id: addition });
assert.match(demo.markup(), /일정이 변경됐어요/);
assert.match(demo.markup(), /class="route-list"/);
assert.match(demo.markup(), /class="pending-additions"/);
assert.ok(demo.markup().includes(`${model.placeById(addition).name}, 추가됨, 재계산 전`));
assert.match(demo.markup(), /class="recommend-card"/);
const secondAddition = model.recommendations(model.addPlace(model.initialDraft(), 0, addition), 0)[0].id;
demo.click('recommend-add', { id: secondAddition });
assert.ok(demo.markup().includes(`${model.placeById(secondAddition).name}, 추가됨, 재계산 전`));
assert.match(demo.markup(), /2곳 · 재계산 전/);
demo.click('pending-remove', { id: secondAddition });
demo.click('toggle-nearby');
assert.match(demo.markup(), /class="pending-additions"/);
demo.click('pending-remove', { id: addition });
assert.doesNotMatch(demo.markup(), /class="pending-additions"/);
demo.click('recommend-add', { id: addition });
demo.click('calculate');
await demo.settle();
assert.match(demo.markup(), /장소 3곳/);
assert.doesNotMatch(demo.markup(), /일정이 변경됐어요/);
assert.doesNotMatch(demo.markup(), /class="pending-additions"/);
demo.change('start-date', '2026-12-01');
assert.ok(demo.markup().includes(model.dateAt('2026-11-10', 0) + '부터'));
assert.match(demo.markup(), /이전 계산 결과/);

